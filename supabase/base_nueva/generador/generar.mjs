// Genera el SQL de la base nueva. Uso, desde la raíz del proyecto:
//   node supabase/base_nueva/generador/generar.mjs
// Entradas: origen.csv, mapa.json, decisiones.json y manual/*.sql
// Salidas:  supabase/base_nueva/sql/*.sql e informe.json
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { cargarOrigen, crearModelo } from './modelo.mjs';
import { reescribir } from './sql.mjs';

const raiz = 'supabase/base_nueva';
const origen = cargarOrigen(`${raiz}/origen.csv`);
const modelo = crearModelo(origen, `${raiz}/mapa.json`);
const decisiones = JSON.parse(readFileSync(`${raiz}/generador/decisiones.json`, 'utf8'));
const informe = [];

const carpetaManual = `${raiz}/generador/manual`;
const manuales = new Map(
  existsSync(carpetaManual)
    ? readdirSync(carpetaManual)
        .filter((n) => n.endsWith('.sql'))
        .map((n) => [n.slice(0, -4), readFileSync(path.join(carpetaManual, n), 'utf8').trim()])
    : [],
);
const quitadas = new Set(decisiones.funciones_quitadas);

const tablas = [...modelo.tablas.values()].filter((t) => t.nuevo && t.origen);
const nombreNuevo = (t) => `${t.esquema}.${t.nuevo}`;
const porNombreViejo = (nombre) => {
  const completo = nombre.includes('.') ? nombre : `public.${nombre}`;
  return modelo.tablas.get(completo);
};

function traducir(texto, objeto, extra = {}) {
  return reescribir(texto, { modelo, nombre: objeto, informe, ...extra });
}

const columnasDe = (tabla, lista) =>
  lista
    .split(',')
    .map((c) => modelo.columnaNueva(tabla, c.trim()) ?? c.trim())
    .join(', ');

function nombreObjeto(tabla, nombre) {
  let resto = nombre.startsWith(`${tabla.viejo}_`) ? nombre.slice(tabla.viejo.length + 1) : nombre;
  const viejas = [...tabla.columnas.keys()].sort((a, b) => b.length - a.length);
  for (const columna of viejas) {
    resto = resto.replace(new RegExp(`(^|_)${columna}(?=_|$)`, 'g'), `$1\u0001${tabla.columnas.get(columna)}\u0001`);
  }
  resto = resto.replaceAll('\u0001', '');
  let final = `${tabla.nuevo}_${resto}`;
  if (final.length > 63) final = `${final.slice(0, 54)}_${hash(final)}`;
  return final;
}

function hash(texto) {
  let h = 2166136261;
  for (const letra of texto) h = Math.imul(h ^ letra.charCodeAt(0), 16777619) >>> 0;
  return h.toString(16).padStart(8, '0');
}

const restricciones = new Map();
for (const tabla of tablas) {
  for (const r of tabla.origen.restricciones ?? []) {
    if (r.tipo === 'n') continue;
    restricciones.set(r.nombre, nombreObjeto(tabla, r.nombre));
  }
  for (const definicion of tabla.origen.indices ?? []) {
    const nombre = definicion.match(/INDEX (\S+) ON/)[1];
    restricciones.set(nombre, nombreObjeto(tabla, nombre));
  }
}

/* ---------- 01: esquemas, tablas, claves e índices ---------- */
const estructura = [
  '-- 01. Extensiones, esquemas, tablas, claves, restricciones e índices.',
  'begin;',
  'create extension if not exists pgcrypto with schema extensions;',
  'create extension if not exists plpgsql_check with schema extensions;',
  'create schema if not exists private;',
  'revoke all on schema private from public;',
  'grant usage on schema private to authenticated;',
  '',
];

for (const tabla of tablas) {
  const columnas = tabla.origen.columnas.map((c) => {
    const partes = [`  ${tabla.columnas.get(c.nombre)} ${c.tipo}`];
    const esSecuencia = c.defecto?.startsWith('nextval(');
    if (c.identidad === 'a') partes.push('generated always as identity');
    else if (c.identidad === 'd' || esSecuencia) partes.push('generated by default as identity');
    if (c.obligatoria) partes.push('not null');
    if (c.defecto !== null && !esSecuencia) {
      const clave = `${tabla.viejo}.${c.nombre}`;
      const especial = decisiones.defectos[clave];
      const valor =
        especial ??
        traducir(c.defecto, `defecto ${clave}`, {
          tablaBase: tabla,
          dominioFijo: modelo.dominio(clave) ? clave : undefined,
        });
      partes.push(`default ${valor}`);
    }
    return partes.join(' ');
  });
  columnas.push(...(decisiones.columnas_agregadas[tabla.viejo] ?? []).map((c) => `  ${c}`));
  estructura.push(`create table ${nombreNuevo(tabla)} (\n${columnas.join(',\n')}\n);`);
  estructura.push(`alter table ${nombreNuevo(tabla)} enable row level security;`, '');
}
estructura.push(...decisiones.sql_tablas_nuevas, '');

const foraneas = [];
const diferidas = [];
for (const tabla of tablas) {
  for (const r of tabla.origen.restricciones ?? []) {
    if (r.tipo === 'n') continue;
    const nombre = restricciones.get(r.nombre);
    const cabeza = `alter table ${nombreNuevo(tabla)} add constraint ${nombre}`;
    if (r.tipo === 'f') {
      const partes = r.definicion.match(/^FOREIGN KEY \(([^)]*)\) REFERENCES ([\w.]+)\(([^)]*)\)(.*)$/);
      const [, propias, referida, ajenas, resto] = partes;
      const destino = porNombreViejo(referida);
      if (destino && !destino.nuevo) {
        informe.push({ objeto: r.nombre, motivo: 'clave foránea hacia tabla quitada', pieza: referida });
        continue;
      }
      const hacia = destino ? `${nombreNuevo(destino)}(${columnasDe(destino, ajenas)})` : `${referida}(${ajenas})`;
      const cola = resto.replace(/(SET (?:NULL|DEFAULT)) \(([^)]*)\)/, (_, a, b) => `${a} (${columnasDe(tabla, b)})`);
      foraneas.push(`${cabeza} foreign key (${columnasDe(tabla, propias)}) references ${hacia}${cola};`);
    } else {
      const definicion = traducir(r.definicion, `restricción ${r.nombre}`, { tablaBase: tabla });
      const linea = `${cabeza} ${definicion};`;
      if (/private\.|public\./.test(definicion)) diferidas.push(linea);
      else estructura.push(linea);
    }
  }
}
estructura.push('', ...decisiones.sql_claves_nuevas_unicas, '');
for (const tabla of tablas) {
  for (const definicion of tabla.origen.indices ?? []) {
    const nombre = definicion.match(/INDEX (\S+) ON/)[1];
    const texto = traducir(definicion.replace(` ${nombre} ON`, ' __indice__ ON'), `índice ${nombre}`, { tablaBase: tabla });
    estructura.push(`${texto.replace('__indice__', restricciones.get(nombre))};`);
  }
}
estructura.push('', ...foraneas, ...decisiones.sql_claves_nuevas_foraneas, 'commit;');

/* ---------- 02: funciones ---------- */
// Columnas que devuelve cada función (RETURNS TABLE): son nombres en inglés y no cambian.
const salidas = new Map();
for (const f of origen.funciones) {
  const tabla = f.definicion.slice(0, f.definicion.indexOf('\n LANGUAGE')).match(/RETURNS TABLE\((.*)\)/s);
  if (!tabla) continue;
  const nombres = [...`,${tabla[1]}`.matchAll(/,\s*([a-z_][a-z0-9_]*) (?=[a-z])/g)].map((m) => m[1]);
  salidas.set(f.nombre, [...(salidas.get(f.nombre) ?? []), ...nombres]);
}
const funciones = [];
const incluidas = [];
for (const f of origen.funciones) {
  if (quitadas.has(f.nombre)) continue;
  const clave = `${f.esquema}.${f.nombre}`;
  incluidas.push(f);
  const reemplazo = manuales.get(clave);
  if (reemplazo) {
    funciones.push({ f, sql: reemplazo.endsWith(';') ? reemplazo : `${reemplazo};` });
    continue;
  }
  const marca = f.definicion.match(/\nAS (\$\w*\$)/);
  const abre = marca.index + marca[0].length;
  const cierra = f.definicion.lastIndexOf(marca[1]);
  const encabezado = f.definicion.slice(0, abre);
  const cuerpo = f.definicion.slice(abre, cierra);
  const variables = [];
  const firma = encabezado.slice(0, encabezado.indexOf('\n LANGUAGE'));
  for (const m of firma.matchAll(/[(,]\s*(?:IN |OUT |INOUT )?([a-z_][a-z0-9_]*) [a-z]/g)) {
    variables.push([m[1], { tabla: null, esRegistro: false, origen: null }]);
  }
  const disparadores = origen.disparadores
    .filter((d) => d.definicion.includes(` ${clave}(`))
    .map((d) => porNombreViejo(d.tabla))
    .filter((t) => t?.nuevo);
  let previo = cuerpo;
  for (const [buscar, poner] of decisiones.cambios_previos[clave] ?? []) {
    if (!previo.includes(buscar)) throw new Error(`${clave}: no se encontró el texto previo: ${buscar}`);
    previo = previo.replaceAll(buscar, poner);
  }
  let nuevoCuerpo = traducir(previo, clave, {
    variables,
    tablasDisparador: disparadores,
    dominiosVariables: { ...decisiones.variables._todas, ...(decisiones.variables[f.nombre] ?? {}) },
    literales: decisiones.literales[f.nombre],
    salidas,
  });
  for (const [buscar, poner] of decisiones.cambios[clave] ?? []) {
    if (!nuevoCuerpo.includes(buscar)) throw new Error(`${clave}: no se encontró el texto a cambiar: ${buscar}`);
    nuevoCuerpo = nuevoCuerpo.replaceAll(buscar, poner);
  }
  const nuevoEncabezado = encabezado.replace(/\b(public|private)\.([a-z_]+)\b(?!\s*\()/g, (todo, esquema, nombre) => {
    const t = modelo.tablas.get(`${esquema}.${nombre}`);
    return t?.nuevo ? nombreNuevo(t) : todo;
  });
  funciones.push({ f, sql: `${nuevoEncabezado}${nuevoCuerpo}${f.definicion.slice(cierra)}`.trimEnd() + ';' });
}
for (const [clave, sql] of manuales) {
  if (!origen.funciones.some((f) => `${f.esquema}.${f.nombre}` === clave)) {
    funciones.push({ f: { esquema: clave.split('.')[0], nombre: clave.split('.')[1], nueva: true }, sql: `${sql.replace(/;$/, '')};` });
  }
}
for (const item of funciones) {
  for (const [viejo, nuevo] of restricciones) {
    if (viejo !== nuevo) item.sql = item.sql.replaceAll(`on constraint ${viejo}`, `on constraint ${nuevo}`).replaceAll(`'${viejo}'`, `'${nuevo}'`);
  }
}

/* ---------- 03: disparadores, políticas, permisos y datos fijos ---------- */
const cierre = ['-- 03. Disparadores, políticas, permisos y catálogo de permisos.', 'begin;', '', ...diferidas, ''];

for (const d of origen.disparadores) {
  const tabla = porNombreViejo(d.tabla);
  if (tabla && !tabla.nuevo) continue;
  if (quitadas.has(d.definicion.match(/EXECUTE FUNCTION \w+\.(\w+)/)[1])) continue;
  const texto = tabla
    ? traducir(d.definicion, `disparador ${d.nombre}`, { tablaBase: tabla, tablasDisparador: [tabla] })
    : d.definicion;
  cierre.push(`${texto};`);
}
cierre.push(...decisiones.sql_disparadores_nuevos, '');

for (const p of origen.politicas) {
  const tabla = modelo.tablas.get(`${p.schemaname}.${p.tablename}`);
  if (!tabla?.nuevo || decisiones.politicas_quitadas.includes(p.policyname)) continue;
  const nombre = nombreObjeto(tabla, p.policyname);
  const expresion = (texto) => traducir(texto, `política ${p.policyname}`, { tablaBase: tabla });
  const roles = Array.isArray(p.roles) ? p.roles : p.roles.replace(/[{}]/g, '').split(',');
  let linea = `create policy ${nombre} on ${nombreNuevo(tabla)} as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${roles.join(', ')}`;
  if (p.qual) linea += `\n  using (${expresion(p.qual)})`;
  if (p.with_check) linea += `\n  with check (${expresion(p.with_check)})`;
  cierre.push(`${linea};`);
}
cierre.push('');

const PRIVILEGIOS = { r: 'select', a: 'insert', w: 'update', d: 'delete', D: 'truncate', x: 'references', t: 'trigger', m: 'maintain' };
const ROLES = ['anon', 'authenticated', 'service_role'];
function concesiones(permisos) {
  return (permisos ?? [])
    .map((p) => p.split('/')[0].split('='))
    .map(([rol, letras]) => ({ rol: rol || 'public', letras }))
    .filter(({ rol }) => rol === 'public' || ROLES.includes(rol));
}

for (const tabla of tablas) {
  const nombre = nombreNuevo(tabla);
  cierre.push(`revoke all on table ${nombre} from public, ${ROLES.join(', ')};`);
  for (const { rol, letras } of concesiones(tabla.origen.permisos)) {
    const lista = [...letras].map((l) => PRIVILEGIOS[l]).filter(Boolean);
    if (lista.length) cierre.push(`grant ${lista.join(', ')} on table ${nombre} to ${rol};`);
  }
  if (decisiones.sin_permisos_por_columna.includes(tabla.viejo)) continue;
  for (const c of tabla.origen.columnas) {
    for (const { rol, letras } of concesiones(c.permisos)) {
      const lista = [...letras].map((l) => PRIVILEGIOS[l]).filter(Boolean);
      for (const privilegio of lista) {
        cierre.push(`grant ${privilegio} (${tabla.columnas.get(c.nombre)}) on table ${nombre} to ${rol};`);
      }
    }
  }
}
cierre.push(...decisiones.sql_permisos_nuevos, '');

const firmaDe = (item) => {
  if (item.f.nueva) return decisiones.firmas_nuevas[`${item.f.esquema}.${item.f.nombre}`];
  const argumentos = item.f.argumentos.replace(/\b(public|private)\.([a-z_]+)\b/g, (todo, e, n) => {
    const t = modelo.tablas.get(`${e}.${n}`);
    return t?.nuevo ? nombreNuevo(t) : todo;
  });
  return `${item.f.esquema}.${item.f.nombre}(${argumentos})`;
};
for (const item of funciones) {
  const firma = firmaDe(item);
  cierre.push(`revoke all on function ${firma} from public, ${ROLES.join(', ')};`);
  const permisos = item.f.nueva ? decisiones.permisos_funciones_nuevas[`${item.f.esquema}.${item.f.nombre}`] : item.f.permisos;
  if (permisos === null) cierre.push(`grant execute on function ${firma} to public;`);
  else {
    for (const { rol } of concesiones(permisos)) cierre.push(`grant execute on function ${firma} to ${rol};`);
  }
}
cierre.push(
  '',
  'alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated, service_role;',
  'alter default privileges for role postgres in schema public grant truncate, references, trigger, maintain on tables to anon, authenticated, service_role;',
  'alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated, service_role;',
  'alter default privileges for role postgres in schema public revoke all on functions from anon, authenticated, service_role;',
  '',
);

const literal = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  if (Array.isArray(v)) return `array[${v.map(literal).join(', ')}]::text[]`;
  return `'${String(v).replaceAll("'", "''")}'`;
};
const catalogo = modelo.tablas.get('public.permission_catalog');
const recursos = modelo.dominio('permission_catalog.resource');
const modulos = modelo.dominio('permission_catalog.module');
const acciones = modelo.dominio('permission_catalog.actions');
const convertir = (columna, valor) => {
  if (valor === null) return null;
  if (columna === 'resource') return recursos[valor] ?? falta(columna, valor);
  if (columna === 'module') return modulos[valor] ?? falta(columna, valor);
  if (columna === 'parent') return recursos[valor] ?? modulos[valor] ?? falta(columna, valor);
  if (columna === 'actions') return valor.map((a) => acciones[a] ?? falta(columna, a));
  return valor;
};
function falta(columna, valor) {
  informe.push({ objeto: 'catálogo de permisos', motivo: `sin traducción en ${columna}`, pieza: valor });
  return valor;
}
const columnasCatalogo = catalogo.origen.columnas.map((c) => c.nombre);
const ordenadas = [...origen.catalogo_permisos].sort((a, b) => Number(b.is_group) - Number(a.is_group) || a.sort - b.sort);
cierre.push(
  `insert into ${nombreNuevo(catalogo)} (${columnasCatalogo.map((c) => catalogo.columnas.get(c)).join(', ')}) values\n${ordenadas
    .map((fila) => `  (${columnasCatalogo.map((c) => literal(convertir(c, fila[c]))).join(', ')})`)
    .join(',\n')};`,
  '',
  'commit;',
);

/* ---------- Escritura ---------- */
mkdirSync(`${raiz}/sql`, { recursive: true });
const encabezado = (n, texto) => `-- ${n}. ${texto}\nbegin;\nset local check_function_bodies = off;\n`;
const mitades = [[], []];
const total = funciones.reduce((a, x) => a + x.sql.length, 0);
let acumulado = 0;
for (const item of funciones) {
  mitades[acumulado < total / 2 ? 0 : 1].push(item.sql);
  acumulado += item.sql.length;
}
writeFileSync(`${raiz}/sql/01_estructura.sql`, `${estructura.join('\n')}\n`);
writeFileSync(`${raiz}/sql/02a_funciones.sql`, `${encabezado('02a', 'Funciones (primera parte).')}\n${mitades[0].join('\n\n')}\n\ncommit;\n`);
writeFileSync(`${raiz}/sql/02b_funciones.sql`, `${encabezado('02b', 'Funciones (segunda parte).')}\n${mitades[1].join('\n\n')}\n\ncommit;\n`);
writeFileSync(`${raiz}/sql/03_permisos_y_datos.sql`, `${cierre.join('\n')}\n`);
writeFileSync(
  `${raiz}/sql/04_proteccion_rls.sql`,
  `-- 04. Activa la seguridad por filas en cualquier tabla nueva (aparte por si pide otro permiso).\n${decisiones.sql_final.join('\n')}\n`,
);
writeFileSync(`${raiz}/generador/informe.json`, `${JSON.stringify(informe, null, 1)}\n`);

const motivos = {};
for (const i of informe) motivos[i.motivo.replace(/".*"|dominio .*/, '')] = (motivos[i.motivo.replace(/".*"|dominio .*/, '')] ?? 0) + 1;
console.log(`tablas ${tablas.length}, funciones ${funciones.length}, manuales ${manuales.size}`);
console.log('pendientes', informe.length, motivos);
